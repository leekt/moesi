import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = fileURLToPath(new URL("../", import.meta.url));
const upstream = dirname(
  fileURLToPath(import.meta.resolve("@openzeppelin/contracts/package.json")),
);
if (
  JSON.parse(readFileSync(resolve(upstream, "package.json"), "utf8")).version !== "5.6.1" ||
  solc.version() !== "0.8.30+commit.73712a01.Emscripten.clang"
)
  throw new Error("proxy_compiler_version");
const sources = {
  "contracts/CheckedBeacon.sol": {
    content: readFileSync(resolve(root, "contracts/CheckedBeacon.sol"), "utf8"),
  },
};
const imported = {};
const settings = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: "shanghai",
  metadata: { bytecodeHash: "none", appendCBOR: false },
  outputSelection: {
    "*": {
      "*": [
        "evm.bytecode.object",
        "evm.deployedBytecode.object",
        "evm.deployedBytecode.immutableReferences",
      ],
    },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify({ language: "Solidity", sources, settings }), {
    import: (name) => {
      if (!name.startsWith("@openzeppelin/contracts/") || name.includes(".."))
        return { error: "unsupported_import" };
      const content = readFileSync(
        resolve(upstream, name.slice("@openzeppelin/contracts/".length)),
        "utf8",
      );
      imported[name] = content;
      return { contents: content };
    },
  }),
);
if (output.errors?.some(({ severity }) => severity === "error"))
  throw new Error("proxy_compilation_failed");
const contracts = output.contracts["contracts/CheckedBeacon.sol"];
const beacon = contracts.CheckedBeacon.evm;
const proxy = contracts.CheckedBeaconProxy.evm;
if (Object.keys(beacon.deployedBytecode.immutableReferences).length !== 0)
  throw new Error("beacon_immutable_unexpected");
const refs = Object.values(proxy.deployedBytecode.immutableReferences);
if (refs.length !== 1 || refs[0].some(({ length }) => length !== 32))
  throw new Error("proxy_immutable_unexpected");
const offsets = refs[0].map(({ start }) => start).sort((a, b) => a - b);
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const sourceHashes = Object.fromEntries(
  Object.entries({
    ...imported,
    "contracts/CheckedBeacon.sol": sources["contracts/CheckedBeacon.sol"].content,
  })
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([name, content]) => [name, sha256(content)]),
);
const generated = `// Generated by bun run --filter moesi generate:proxy-artifacts. Do not edit.\n// OpenZeppelin Contracts 5.6.1 (MIT); see THIRD_PARTY_NOTICES.md.\nexport const CHECKED_BEACON_INIT_CODE =\n  "0x${beacon.bytecode.object}";\nexport const CHECKED_BEACON_RUNTIME =\n  "0x${beacon.deployedBytecode.object}";\nexport const CHECKED_PROXY_INIT_CODE =\n  "0x${proxy.bytecode.object}";\nexport const CHECKED_PROXY_RUNTIME =\n  "0x${proxy.deployedBytecode.object}";\nexport const CHECKED_PROXY_BEACON_OFFSETS = [${offsets.join(", ")}] as const;\n`;
const provenance = `${JSON.stringify({ upstream: "@openzeppelin/contracts@5.6.1", compiler: solc.version(), settings, sourceSha256: sourceHashes, generatedSha256: sha256(generated) }, null, 2)}\n`;
for (const [name, contents] of [
  ["src/strategy/proxy-artifacts.ts", generated],
  ["contracts/provenance.json", provenance],
]) {
  const path = resolve(root, name);
  if (process.argv[2] === "--write") writeFileSync(path, contents);
  else if (readFileSync(path, "utf8") !== contents) throw new Error("proxy_artifact_mismatch");
}
